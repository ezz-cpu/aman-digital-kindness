import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
await Promise.all(['aman-scene', 'tobi'].map(name => build({
  entryPoints: [path.join(root, `${name}.js`)],
  outfile: path.join(root, `${name}.bundle.js`),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  legalComments: 'inline',
  banner: { js: `/* Generated by tools/build-scene.mjs. Edit ${name}.js, then rebuild. ${name === 'aman-scene' ? 'Three.js: MIT; see vendor/three/LICENSE.txt.' : ''} */` },
})));
console.log('Built aman-scene.bundle.js and tobi.bundle.js for HTTP and direct local-file opening.');
